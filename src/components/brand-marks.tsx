/**
 * ブランドマーク（§5.1 の例外、DECISION U-38）
 *
 * 各社の公式素材（assets/brand/*.svg）の path を**そのまま**写したインライン SVG。
 * Tabler の `brand-*` は第三者による再描画で、各社の規約に抵触する:
 * X「形の完全性を保つ」/ GitHub「色・寸法の変更を含め改変不可」/
 * Discord「編集・変更・歪曲・再配色・再構成をしない」/ Instagram「Brand Resource Center の
 * ロゴのみ使用」。ここでは幾何に手を加えず、色だけを `currentColor`（行の文字色 =
 * 明るい面で黒、墨面で白）で塗る — 4 社とも黒 / 白のモノクロを許容している。
 *
 * viewBox は素材のまま。マークの縦横比は揃っていない（Discord は 1.32:1）ので、
 * 呼び出し側が与える正方形の枠（`size-icon-*`）の中で `xMidYMid meet` の既定により
 * 中央に収まる。素材を更新するときは assets/brand/ を差し替え、path を写し直す。
 *
 * すべて装飾（`aria-hidden`）。行き先の名前は隣接するテキストか visually-hidden が運ぶ
 * （§6.15 / §6.17）。
 */
export type BrandMarkProps = Omit<
  ComponentProps<"svg">,
  "aria-hidden" | "focusable" | "viewBox" | "fill" | "stroke" | "strokeWidth"
> & {
  /** Tabler と同じ径の指定。既定 20 = icon/md。ページではクラス（`size-icon-*`）で与える */
  size?: number | string;
  /** Tabler 互換のために受けるだけ。塗りのマークに線は引かない */
  stroke?: number | string;
};

function mark(displayName: string, viewBox: string, path: React.ReactNode) {
  function Mark({ size = 20, stroke: _stroke, ...props }: BrandMarkProps) {
    return (
      <svg
        aria-hidden="true"
        fill="currentColor"
        focusable="false"
        height={size}
        viewBox={viewBox}
        width={size}
        xmlns="http://www.w3.org/2000/svg"
        {...props}
      >
        {path}
      </svg>
    );
  }
  Mark.displayName = displayName;
  return Mark;
}

